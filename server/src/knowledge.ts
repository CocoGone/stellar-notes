export function brightnessPlain(raw?: string): string | undefined {
  if (!raw) return undefined;
  if (raw === '庙' || raw === '旺') return `${raw}：这颗星的特质比较容易顺利发挥`;
  if (raw === '得' || raw === '利' || raw === '地') return `${raw}：发挥得还不错`;
  if (raw === '平') return '平：发挥得中规中矩';
  if (raw === '不' || raw === '陷' || raw === '闲') return `${raw}：力量受限，特质可能用得比较辛苦`;
  return undefined;
}

